// Turns every CV version in cv/roles/ into its own page before the site builds.
//
//   cv/roles/<role>.md  ->  /cv/<role>        (hidden: no-index, not in the sitemap or menus)
//                           /cv/<role>.pdf    (made by cv-pdfs.mjs after the build)
//   cv/DEFAULT          ->  /cv  and  /Vidya_Patil_CV.pdf   (the version in the menu)
//
// Run `node scripts/cv-sync.mjs --list` to see every version and its link.
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const rolesDir = path.join(root, 'cv', 'roles');
const pagesDir = path.join(root, 'src', 'pages');
const site = 'https://vidyap18.github.io';

export function readRoles() {
  return fs
    .readdirSync(rolesDir)
    .filter((f) => f.endsWith('.md'))
    .map((f) => f.replace(/\.md$/, ''))
    .sort();
}

export function defaultRole() {
  const file = path.join(root, 'cv', 'DEFAULT');
  const name = fs.existsSync(file) ? fs.readFileSync(file, 'utf8').trim() : 'general';
  if (!readRoles().includes(name)) {
    throw new Error(`cv/DEFAULT names "${name}", but there is no cv/roles/${name}.md`);
  }
  return name;
}

function render(source, {pdf, hidden}) {
  // Drop any download link written by hand, then add the right one before the first section.
  let body = source.replace(/^<p className="cv-download">.*<\/p>\n?/m, '');
  const link = `<p className="cv-download"><a href="${pdf}" download>Download CV (PDF)</a></p>\n\n`;
  body = body.replace(/^## /m, `${link}## `);
  const note = '{/* Generated by scripts/cv-sync.mjs from cv/roles. Edit the files in cv/roles instead. */}\n';
  const head = hidden ? '\n<head>\n  <meta name="robots" content="noindex, nofollow" />\n</head>\n' : '';
  // Insert after the closing front matter delimiter.
  return body.replace(/\n---\n/, `\n---\n\n${note}${head}`);
}

function sync() {
  const roles = readRoles();
  const def = defaultRole();
  fs.rmSync(path.join(pagesDir, 'cv'), {recursive: true, force: true});
  fs.mkdirSync(path.join(pagesDir, 'cv'), {recursive: true});
  for (const role of roles) {
    const src = fs.readFileSync(path.join(rolesDir, `${role}.md`), 'utf8');
    fs.writeFileSync(path.join(pagesDir, 'cv', `${role}.mdx`), render(src, {pdf: `/cv/${role}.pdf`, hidden: true}));
  }
  const defSrc = fs.readFileSync(path.join(rolesDir, `${def}.md`), 'utf8');
  fs.writeFileSync(path.join(pagesDir, 'cv.mdx'), render(defSrc, {pdf: '/Vidya_Patil_CV.pdf', hidden: false}));
  fs.rmSync(path.join(pagesDir, 'cv.md'), {force: true});
  console.log(`CV pages: /cv (${def}) and ${roles.map((r) => `/cv/${r}`).join(', ')}`);
}

function list() {
  const def = defaultRole();
  console.log(`Menu CV (/cv): ${def}\n`);
  for (const role of readRoles()) {
    console.log(`${role.padEnd(24)} ${site}/cv/${role}    PDF: ${site}/cv/${role}.pdf`);
  }
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  if (process.argv.includes('--list')) list();
  else sync();
}
